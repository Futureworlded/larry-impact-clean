-- One home for every money record: the ledger, payout batches and their lines,
-- order events, fraud flags, order locks, split versions and the audit log move
-- from WordPress into Supabase, and a product's rescue payout lives only in
-- products.rescue_cents. IDs start at 1000000 so rows copied from WordPress keep
-- their original IDs without colliding with new ones.

alter table products add column if not exists rescue_cents integer check (rescue_cents is null or rescue_cents >= 0);

create table if not exists ledger (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz not null default now(),
  entry_type text not null,
  order_ref text not null default '',
  product_id text not null default '',
  rescue_id text not null default '',
  amount_cents bigint not null default 0,
  net_cents bigint not null default 0,
  meta text,
  source text not null default ''
);
create index if not exists ledger_entry_type on ledger (entry_type);
create index if not exists ledger_order_ref on ledger (order_ref);
create index if not exists ledger_rescue_id on ledger (rescue_id);

create table if not exists payout_batches (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz not null default now(),
  rescue_id text not null,
  amount_cents bigint not null default 0,
  transfer_id text not null default '',
  status text not null default 'pending',
  notes text
);
create index if not exists payout_batches_rescue_id on payout_batches (rescue_id);
create index if not exists payout_batches_status on payout_batches (status);
create unique index if not exists payout_batches_transfer_id on payout_batches (transfer_id) where transfer_id <> '';

create table if not exists payout_lines (
  id bigint generated by default as identity (start with 1000000) primary key,
  payout_id bigint not null references payout_batches(id) on delete cascade,
  order_ref text not null default '',
  amount_cents bigint not null default 0
);
create index if not exists payout_lines_payout_id on payout_lines (payout_id);
create index if not exists payout_lines_order_ref on payout_lines (order_ref);

create table if not exists audit_log (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz not null default now(),
  actor text not null default 'system',
  action text not null,
  object_type text not null default '',
  object_id text not null default '',
  details text,
  ip_address text not null default ''
);
create index if not exists audit_log_action on audit_log (action);

create table if not exists fraud_flags (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz not null default now(),
  flag_type text not null,
  order_ref text not null default '',
  product_id text not null default '',
  rescue_id text not null default '',
  details text,
  resolved boolean not null default false
);

create table if not exists order_locks (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz not null default now(),
  order_ref text not null unique,
  locked_at timestamptz not null default now()
);

create table if not exists split_versions (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz not null default now(),
  product_id text not null,
  version integer not null default 1,
  rescue_percent numeric(7,3) not null default 0,
  larry_percent numeric(7,3) not null default 0,
  cost_percent numeric(7,3) not null default 0,
  effective_from timestamptz not null default now(),
  created_by bigint not null default 0
);
create index if not exists split_versions_product on split_versions (product_id, effective_from);

create table if not exists order_events (
  id bigint generated by default as identity (start with 1000000) primary key,
  created_at timestamptz,
  updated_at timestamptz,
  source text not null default '',
  topic text not null default '',
  external_id text not null default '',
  order_ref text not null default '',
  signature text not null default '',
  result text not null default 'received',
  attempts integer not null default 0,
  details text,
  payload text,
  resolved boolean not null default false,
  resolved_at timestamptz,
  resolved_by bigint not null default 0
);
create index if not exists order_events_external on order_events (source, external_id);
create index if not exists order_events_open on order_events (resolved, result);

-- Only the plugin's server key may touch these tables.
alter table ledger enable row level security;
alter table payout_batches enable row level security;
alter table payout_lines enable row level security;
alter table audit_log enable row level security;
alter table fraud_flags enable row level security;
alter table order_locks enable row level security;
alter table split_versions enable row level security;
alter table order_events enable row level security;
revoke all on ledger, payout_batches, payout_lines, audit_log, fraud_flags, order_locks, split_versions, order_events from anon, authenticated;
grant select, insert, update, delete on ledger, payout_batches, payout_lines, audit_log, fraud_flags, order_locks, split_versions, order_events to service_role;
grant usage, select on all sequences in schema public to service_role;

-- The ledger and audit log are append-only: rows can be added but never changed or deleted.
create or replace function li_block_change() returns trigger language plpgsql as $$
begin
  raise exception '% is append-only', tg_table_name;
end $$;
drop trigger if exists ledger_append_only on ledger;
create trigger ledger_append_only before update or delete on ledger for each row execute function li_block_change();
drop trigger if exists audit_log_append_only on audit_log;
create trigger audit_log_append_only before update or delete on audit_log for each row execute function li_block_change();
